/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_SPI1_Init();
  MX_USART1_UART_Init();
  MX_USART2_UART_Init();
  MX_USART3_UART_Init();
  /* USER CODE BEGIN 2 */
  /* 初始化 BSP 模块 */
  JY901S_Init(&g_jy901s, &huart2);

  /* 初始化舵机（ID, 角度范围） */
  Servo_Init(&g_servo_pitch, &huart3, 1, 0.0f, 300.0f);
  Servo_Init(&g_servo_roll,  &huart3, 2, 0.0f, 300.0f);
  Servo_Init(&g_servo_yaw,   &huart3, 3, 100.0f, 200.0f);

  /* 初始化 PID 控制器 */
  PID_Init(&g_pid_pitch, 0.4f, 0.1f, 0.1f);
  PID_Init(&g_pid_roll,  0.4f, 0.12f, 0.12f);
  PID_Init(&g_pid_yaw,   0.4f, 0.1f, 0.2f);

  /* 设置 PID 限幅参数（与原始 Keil 工程一致） */
  PID_SetLimits(&g_pid_pitch, 0.5f,  550.0f, 1000.0f);
  PID_SetLimits(&g_pid_roll,  1.0f,  450.0f, 1000.0f);
  PID_SetLimits(&g_pid_yaw,   1.0f,  300.0f, 1000.0f);

  /* 启动 JY901S 中断接收 */
  JY901S_StartReceive();

  /* 等待系统稳定 */
  HAL_Delay(500);
  LED_ON();
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE BEGIN 3 */
    /* 检查 JY901S 是否有新数据 */
    if (JY901S_IsDataReady(&g_jy901s)) {
      JY901S_ClearDataReady(&g_jy901s);

      /* PID 计算补偿量 */
      float pitch_out = PID_Compute(&g_pid_pitch, 0.0f, g_jy901s.pitch);
      float roll_out  = PID_Compute(&g_pid_roll,  0.0f, g_jy901s.roll);
      float yaw_out   = -PID_Compute(&g_pid_yaw, -143.0f, g_jy901s.yaw);

      /* 控制舵机 */
      Servo_SetPosition(&g_servo_pitch, 240.0f + pitch_out, 270);
      Servo_SetPosition(&g_servo_roll,  150.0f + roll_out,  270);
      Servo_SetPosition(&g_servo_yaw,   150.0f + yaw_out,   250);

      /* 串口打印 IMU 采集数据 */
      printf("===== IMU Data =====\r\n");
      printf("Angle  -> Pitch: %8.2f deg  Roll: %8.2f deg  Yaw: %8.2f deg\r\n",
             g_jy901s.pitch, g_jy901s.roll, g_jy901s.yaw);
      printf("Gyro   -> Wx: %8.2f deg/s  Wy: %8.2f deg/s  Wz: %8.2f deg/s\r\n",
             g_jy901s.wx, g_jy901s.wy, g_jy901s.wz);
      printf("PID Out-> Pitch: %8.2f  Roll: %8.2f  Yaw: %8.2f\r\n",
             pitch_out, roll_out, yaw_out);
      printf("====================\r\n");

      LED_Toggle();
    }
  }
  /* USER CODE END 3 */
}

